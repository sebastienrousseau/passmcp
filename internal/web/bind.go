package web

import "net"

// isLoopback reports whether a bind host is this machine only. An empty
// host is not: net.Listen reads ":8080" as every interface.
func isLoopback(host string) bool {
	if host == "localhost" {
		return true
	}
	ip := net.ParseIP(host)
	return ip != nil && ip.IsLoopback()
}
