//go:build linux

package engine

import (
	"os"
	"strings"
)

// kernelRelease is the running kernel's release, as uname -r prints it.
func kernelRelease() string {
	b, err := os.ReadFile("/proc/sys/kernel/osrelease")
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(b))
}
